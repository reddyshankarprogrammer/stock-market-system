import com.stockmarket.accountservice.service.model.FeeBreakdown;
import com.stockmarket.accountservice.service.model.FeeCharge;
import com.stockmarket.accountservice.service.model.TaxBreakdown;
import com.stockmarket.accountservice.service.model.TaxCharge;
import org.mapstruct.Mapper;
import org.mapstruct.Mapping;
import org.mapstruct.Named;
import org.mapstruct.ReportingPolicy;

import java.math.BigDecimal;
import java.util.Arrays;
import java.util.List;

/**
 * Entity to response DTO mappings, generated by MapStruct at compile time.
 *
 * {@code unmappedTargetPolicy = ERROR} makes the build fail when a response field
 * is added without a mapping, so DTOs cannot silently return nulls.
 */
@Mapper(componentModel = "spring", unmappedTargetPolicy = ReportingPolicy.ERROR)
public interface AccountMapper {

    AccountResponse toAccountResponse(InvestmentAccount account);

    List<AccountResponse> toAccountResponses(List<InvestmentAccount> accounts);

    @Mapping(target = "accountId", source = "account.id")
    @Mapping(target = "statementId", source = "statement.id")
    @Mapping(target = "quantity", source = "quantity", qualifiedByName = "plainQuantity")
    @Mapping(target = "balanceAfter", ignore = true)
    TradeResponse toTradeResponse(Trade trade);

    List<TradeResponse> toTradeResponses(List<Trade> trades);

    /**
     * Stored valuation snapshot; {@code HoldingService} overwrites it with live prices when available.
     */
    @Mapping(target = "accountId", source = "account.id")
    @Mapping(target = "quantity", source = "quantity", qualifiedByName = "plainQuantity")
    @Mapping(target = "investedAmount", source = "totalCost")
    @Mapping(target = "unrealizedProfit", source = "unrealizedPnl")
    @Mapping(target = "unrealizedProfitPercent", ignore = true)
    HoldingResponse toHoldingResponse(Holding holding);

    LedgerResponse toLedgerResponse(AccountLedger entry);

    List<LedgerResponse> toLedgerResponses(List<AccountLedger> entries);

    @Mapping(target = "accountId", source = "account.id")
    FundTransactionResponse toFundTransactionResponse(AccountFundTransaction transaction);

    List<FundTransactionResponse> toFundTransactionResponses(List<AccountFundTransaction> transactions);

    @Mapping(target = "accountId", source = "account.id")
    @Mapping(target = "quantity", source = "quantity", qualifiedByName = "plainQuantity")
    DividendResponse toDividendResponse(Dividend dividend);

    List<DividendResponse> toDividendResponses(List<Dividend> dividends);

    @Mapping(target = "accountId", source = "account.id")
    InterestResponse toInterestResponse(InterestTransaction interest);

    List<InterestResponse> toInterestResponses(List<InterestTransaction> interest);

    FeeMasterResponse toFeeMasterResponse(FeeMaster feeMaster);

    List<FeeMasterResponse> toFeeMasterResponses(List<FeeMaster> feeMasters);

    TaxMasterResponse toTaxMasterResponse(TaxMaster taxMaster);

    List<TaxMasterResponse> toTaxMasterResponses(List<TaxMaster> taxMasters);

    @Mapping(target = "accountId", source = "account.id")
    @Mapping(target = "feeCode", source = "feeMaster.code")
    @Mapping(target = "tradeId", source = "trade.id")
    @Mapping(target = "fundTransactionId", source = "fundTransaction.id")
    AccountFeeResponse toAccountFeeResponse(AccountFee fee);

    List<AccountFeeResponse> toAccountFeeResponses(List<AccountFee> fees);

    @Mapping(target = "accountId", source = "account.id")
    @Mapping(target = "taxCode", source = "taxMaster.code")
    @Mapping(target = "tradeId", source = "trade.id")
    @Mapping(target = "dividendId", source = "dividend.id")
    @Mapping(target = "statementId", source = "statement.id")
    AccountTaxResponse toAccountTaxResponse(AccountTax tax);

    List<AccountTaxResponse> toAccountTaxResponses(List<AccountTax> taxes);

    @Mapping(target = "accountId", source = "account.id")
    @Mapping(target = "tradeId", source = "trade.id")
    @Mapping(target = "statementId", source = "statement.id")
    AccountChargeResponse toAccountChargeResponse(AccountCharge charge);

    List<AccountChargeResponse> toAccountChargeResponses(List<AccountCharge> charges);

    AuditLogResponse toAuditLogResponse(AuditLog auditLog);

    List<AuditLogResponse> toAuditLogResponses(List<AuditLog> auditLogs);

    @Mapping(target = "accountId", source = "account.id")
    @Mapping(target = "latestImport", ignore = true)
    AccountStatementResponse toStatementResponse(AccountStatement statement);

    @Mapping(target = "statementId", source = "statement.id")
    @Mapping(target = "warnings", source = "warnings", qualifiedByName = "warningLines")
    StatementImportHistoryResponse toImportHistoryResponse(StatementImportHistory history);

    List<StatementImportHistoryResponse> toImportHistoryResponses(List<StatementImportHistory> history);

    @Mapping(target = "accountId", source = "account.id")
    @Mapping(target = "brokerName", source = "account.brokerName")
    PerformanceResponse toPerformanceResponse(AccountPerformance performance);

    @Mapping(target = "code", source = "feeMaster.code")
    @Mapping(target = "type", source = "feeMaster.feeType")
    ChargeLineResponse toChargeLine(FeeCharge charge);

    @Mapping(target = "code", source = "taxMaster.code")
    @Mapping(target = "type", source = "taxMaster.taxType")
    @Mapping(target = "baseAmount", source = "taxableAmount")
    ChargeLineResponse toChargeLine(TaxCharge charge);

    @Mapping(target = "fees", source = "charges")
    @Mapping(target = "totalFees", source = "total")
    FeeBreakdownResponse toFeeBreakdownResponse(FeeBreakdown breakdown);

    @Mapping(target = "taxes", source = "charges")
    @Mapping(target = "totalTax", source = "total")
    TaxBreakdownResponse toTaxBreakdownResponse(TaxBreakdown breakdown);

    /**
     * Quantities are stored with 8 decimals; responses drop the trailing zeros, so whole
     * share counts stay whole numbers ({@code 10}, not {@code 10.00000000}) as before v2.
     */
    @Named("plainQuantity")
    default BigDecimal plainQuantity(BigDecimal quantity) {
        if (quantity == null) {
            return null;
        }
        BigDecimal stripped = quantity.stripTrailingZeros();
        return stripped.scale() < 0 ? stripped.setScale(0) : stripped;
    }

    /**
     * Warnings are stored newline-separated.
     */
    @Named("warningLines")
    default List<String> warningLines(String warnings) {
        if (warnings == null || warnings.isBlank()) {
            return List.of();
        }
        return Arrays.stream(warnings.split("\n")).filter(line -> !line.isBlank()).toList();
    }
}
